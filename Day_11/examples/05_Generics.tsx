// =========================================================================
// الدرس الخامس: الأنواع العامة (Generics - <T>)
// =========================================================================
// Generics تعطينا ميزة رائعة: "المرونة القصوى مع الأمان التام".
// فبدلاً من استخدام any الذي يدمر أمان TypeScript، نستخدم <T> لتمثيل "نوع غير معروف سيتم تحديده لاحقاً".

// ❌ الطريقة الأولى السيئة: استخدام any (كارثة سيبرانية وهندسية!)
function getFirstElementBad(array: any[]): any {
  return array[0];
}

// عندما نستدعيها ونمرر قائمة نصوص، المحرك يصبح أعمى تماماً:
const badResult = getFirstElementBad(["أحمد", "سارة"]);
// المحرك يظن أن badResult هو any! بالتالي لو كتبت badResult. وطلبت دالة غير موجودة،
// فلن يمنعك المحرر وسيتم تشغيل الكود وينفجر في وجه المستخدم! 💥

// =========================================================================

// ✅ الطريقة الثانية الممتازة: استخدام Generics <T> (الذكاء الخارق!)
function getFirstElement<T>(array: T[]): T {
  return array[0];
}

// 🪄 انظر السحر الآن:
const goodResult = getFirstElement(["أحمد", "سارة"]); 
// المحرك استنتج آلياً أن T هي (string)! بالتالي عرف أن المتغير goodResult هو نص (string) 100%!
// وسيمنحك كل دوال النصوص في VS Code مثل (toUpperCase) ويمسح أي احتمال للخطأ! 🛡️

// تعمل أيضاً مع الأرقام تلقائياً بدون الحاجة لتكرار الكود:
const firstNumber = getFirstElement([10, 20, 30]); // استنتج أن T هي (number)
